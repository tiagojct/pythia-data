"""Bootstrap confidence intervals for the era trends in negative content.

Usage:
    uv run scripts/analyse_era_ci.py

Reads data/analysis/timeline_model.csv, anchors_model.csv and anchors_model_event.csv
(written by analyse_timeline.py and analyse_anchors.py; run those first).
Writes data/analysis/era_ci.md.

Added 2026-11-20 for the Futures paper (research/pythia-futures), with the author's approval.
Unit: the model (n = 24). Era is the listing year group, ordinal. Each bootstrap sample
draws 24 models with replacement. Percentile 95% intervals. The catastrophe residual is
re-fitted in each sample, because the fit across models is part of the estimate.
The interval covers the variation between models only; the runs within a model are fixed.
"""

import csv
import math
import random
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AN = ROOT / "data" / "analysis"
OUT = AN / "era_ci.md"
REPS = 10_000
SEED = 20261120


def ranks(v):
    order = sorted(range(len(v)), key=lambda i: v[i])
    out = [0.0] * len(v)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
            j += 1
        for k in range(i, j + 1):
            out[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return out


def spearman(x, y):
    try:
        return st.correlation(ranks(x), ranks(y))
    except st.StatisticsError:
        return None


def partial(era, y, z):
    """Spearman partial correlation of era and y, controlling for z (same formula as analyse_timeline.py)."""
    r_ey, r_ez, r_yz = spearman(era, y), spearman(era, z), spearman(y, z)
    if None in (r_ey, r_ez, r_yz):
        return None
    den = (1 - r_ez ** 2) * (1 - r_yz ** 2)
    return (r_ey - r_ez * r_yz) / math.sqrt(den) if den > 0 else None


def residual_trend(era, cat, rest):
    """Spearman of era and the catastrophe residual, after OLS of catastrophe on rest across models."""
    try:
        slope, intercept = st.linear_regression(rest, cat)
    except st.StatisticsError:
        return None
    res = [c - (intercept + slope * n) for c, n in zip(cat, rest)]
    return spearman(era, res)


def read(name):
    with open(AN / name, newline="") as f:
        return list(csv.DictReader(f))


def main():
    tl = {r["model"]: r for r in read("timeline_model.csv")}
    an = {r["model"]: r for r in read("anchors_model.csv")}
    ext = {r["model"]: r for r in read("anchors_model_event.csv") if r["anchor"] == "extinction"}

    rows = []
    for m, t in tl.items():
        a, e = an.get(m), ext.get(m)
        rows.append({
            "model": m,
            "era": int(t["era"]),
            "neg": float(t["share_negative"]),
            "len": float(t["events_per_run"]),
            "cat": float(a["index_catastrophe"]) if a and a["index_catastrophe"] else None,
            "rest": float(a["index_non_catastrophe"]) if a and a["index_non_catastrophe"] else None,
            "ext": float(e["median_prob"]) if e and e["median_prob"] else None,
        })

    def stats(sample):
        era = [r["era"] for r in sample]
        out = {
            "primary": spearman(era, [r["neg"] for r in sample]),
            "length": partial(era, [r["neg"] for r in sample], [r["len"] for r in sample]),
        }
        s = [r for r in sample if r["cat"] is not None and r["rest"] is not None]
        out["residual"] = residual_trend([r["era"] for r in s], [r["cat"] for r in s], [r["rest"] for r in s])
        s = [r for r in sample if r["ext"] is not None]
        out["extinction"] = spearman([r["era"] for r in s], [r["ext"] for r in s])
        return out

    point = stats(rows)
    rng = random.Random(SEED)
    boots = {k: [] for k in point}
    for _ in range(REPS):
        sample = [rng.choice(rows) for _ in rows]
        for k, v in stats(sample).items():
            if v is not None:
                boots[k].append(v)

    def ci(v):
        v = sorted(v)
        lo = v[int(0.025 * (len(v) - 1))]
        hi = v[int(math.ceil(0.975 * (len(v) - 1)))]
        return lo, hi

    labels = {
        "primary": "Era and negative share of timeline events (primary)",
        "length": "Same, partial, controlling for events per run",
        "residual": "Era and anchor catastrophe residual (refitted in each sample)",
        "extinction": "Era and median extinction probability",
    }
    n = {k: sum(1 for r in rows if (k != "residual" or r["cat"] is not None) and (k != "extinction" or r["ext"] is not None))
         for k in point}
    L = ["# Era trends: bootstrap intervals", "",
         "Generated by scripts/analyse_era_ci.py. Do not edit.", "",
         f"Model-level percentile bootstrap, {REPS} samples, seed {SEED}. Spearman correlations across models.",
         "Samples where a statistic is undefined (for example one era only) are dropped; the count is shown.",
         "The interval covers the variation between models only.", "",
         "| statistic | models | estimate | 95% CI | samples used |", "|---|---|---|---|---|"]
    for k, lab in labels.items():
        lo, hi = ci(boots[k])
        L.append(f"| {lab} | {n[k]} | {point[k]:.2f} | {lo:.2f} to {hi:.2f} | {len(boots[k])} |")
    # Sensitivity: the primary statistic without the 2023 models (only two models in that era).
    sub = [r for r in rows if r["era"] != 2023]
    est = spearman([r["era"] for r in sub], [r["neg"] for r in sub])
    vals = []
    for _ in range(REPS):
        s = [rng.choice(sub) for _ in sub]
        v = spearman([r["era"] for r in s], [r["neg"] for r in s])
        if v is not None:
            vals.append(v)
    lo, hi = ci(vals)
    L.append(f"| Primary, without the 2023 models (sensitivity) | {len(sub)} | {est:.2f} | {lo:.2f} to {hi:.2f} | {len(vals)} |")
    # Vendor: compare only models of the same vendor from different eras (the vendor prefix of the
    # model id; meta-llama merged with meta). Statistic: share of such pairs in which the later model
    # has the larger negative share (ties count one half). P-value: permutation of the eras within
    # each vendor, two-sided (distance from 0.5), same seed stream. Two-sided because PLAN.md
    # pre-specified the opposite direction.
    def vendor(m):
        v = m.split("/")[0]
        return "meta" if v == "meta-llama" else v

    by_v = {}
    for r in rows:
        by_v.setdefault(vendor(r["model"]), []).append(r)

    def pair_score(groups):
        conc = n_pairs = 0.0
        for g in groups.values():
            for i in range(len(g)):
                for j in range(i + 1, len(g)):
                    a, b = g[i], g[j]
                    if a["era"] == b["era"]:
                        continue
                    lo_, hi_ = (a, b) if a["era"] < b["era"] else (b, a)
                    n_pairs += 1
                    conc += 1 if hi_["neg"] > lo_["neg"] else 0.5 if hi_["neg"] == lo_["neg"] else 0
        return conc, n_pairs

    conc, n_pairs = pair_score(by_v)
    obs = conc / n_pairs
    hits = 0
    for _ in range(REPS):
        perm = {}
        for v, g in by_v.items():
            eras = [r["era"] for r in g]
            rng.shuffle(eras)
            perm[v] = [{**r, "era": e} for r, e in zip(g, eras)]
        c, n_ = pair_score(perm)
        if n_ and abs(c / n_ - 0.5) >= abs(obs - 0.5) - 1e-12:
            hits += 1
    multi = sorted(v for v, g in by_v.items() if len({r["era"] for r in g}) > 1)
    L += ["", "## Within vendor", "",
          f"Vendors with models in more than one era: {len(multi)} ({', '.join(multi)}).",
          f"Pairs of models from the same vendor and different eras: {int(n_pairs)}. "
          f"The later model has the larger negative share in {conc:g} ({obs:.2f}).",
          f"Permutation of eras within vendor, {REPS} samples, two-sided: p = {(hits + 1) / (REPS + 1):.4f}."]
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
